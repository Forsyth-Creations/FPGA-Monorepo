//! Generates base-address constants from the Vivado block design's address map.
//!
//! `fpga/scripts/build.tcl` writes `fpga/dist/address_map.json` during
//! `build_platform`; this turns each entry into a module of `const`s. The
//! register layout *within* a peripheral is not in that file -- it is
//! hand-written per IP type in `src/ip/`, and keyed to the VLNV recorded here
//! so a mismatch is caught at build time rather than by a hung AXI read.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::PathBuf;

/// Escape hatch for checkouts that have never run Vivado: emits an empty map
/// instead of failing, so `cargo check` still works.
const ALLOW_MISSING: &str = "XIL_BINDINGS_ALLOW_MISSING";

struct Peripheral {
    instance: String,
    vlnv: String,
    offset: u64,
    range: u64,
}

fn main() {
    let manifest_dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let map_path = manifest_dir.join("../../fpga/dist/address_map.json");

    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed={}", map_path.display());
    println!("cargo:rerun-if-env-changed={ALLOW_MISSING}");

    let peripherals = match std::fs::read_to_string(&map_path) {
        Ok(text) => parse(&text),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
            if std::env::var_os(ALLOW_MISSING).is_some() {
                println!(
                    "cargo:warning=xil_bindings: {} not found, generating an empty address map",
                    map_path.display()
                );
                Vec::new()
            } else {
                panic!(
                    "xil_bindings: {} not found.\n\
                     Run `yarn build_platform` (or `turbo build_platform`) to build the \
                     hardware platform first, or set {ALLOW_MISSING}=1 to generate an \
                     empty map.",
                    map_path.display()
                );
            }
        }
        Err(e) => panic!("xil_bindings: reading {}: {e}", map_path.display()),
    };

    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("address_map.rs");
    std::fs::write(&out, codegen(&peripherals)).expect("writing generated bindings");
}

/// Minimal reader for the flat array-of-objects that build.tcl emits. Every
/// value is a quoted string, and there is no nesting, so a full JSON parser
/// would just be a dependency for this crate to drag onto the host.
fn parse(text: &str) -> Vec<Peripheral> {
    let mut out = Vec::new();
    for (n, raw) in text.split('{').skip(1).enumerate() {
        let body = raw.split('}').next().unwrap_or_default();
        let field = |key: &str| -> String {
            let needle = format!("\"{key}\"");
            let after = body
                .find(&needle)
                .and_then(|i| body[i + needle.len()..].find(':').map(|j| i + needle.len() + j + 1))
                .unwrap_or_else(|| panic!("xil_bindings: entry {n} has no `{key}` field"));
            let rest = &body[after..];
            let start = rest.find('"').expect("quoted value") + 1;
            let end = rest[start..].find('"').expect("closing quote") + start;
            rest[start..end].to_string()
        };
        let hex = |key: &str| -> u64 {
            let v = field(key);
            let digits = v.strip_prefix("0x").or_else(|| v.strip_prefix("0X")).unwrap_or(&v);
            u64::from_str_radix(digits, 16)
                .unwrap_or_else(|e| panic!("xil_bindings: `{key}` = {v:?} is not hex: {e}"))
        };
        out.push(Peripheral {
            instance: field("instance"),
            vlnv: field("vlnv"),
            offset: hex("offset"),
            range: hex("range"),
        });
    }
    out
}

fn codegen(peripherals: &[Peripheral]) -> String {
    let mut s = String::new();
    s.push_str("// @generated by build.rs from fpga/dist/address_map.json -- do not edit.\n\n");

    for p in peripherals {
        let module = sanitize(&p.instance);
        // The IP version is deliberately part of the constant: a driver in
        // src/ip/ asserts against it, so bumping an IP core in Vivado without
        // revisiting the register map fails the build.
        writeln!(s, "/// `{}` @ `{:#010x}`", p.vlnv, p.offset).unwrap();
        writeln!(s, "pub mod {module} {{").unwrap();
        writeln!(s, "    /// Base address in the PS `Data` address space.").unwrap();
        writeln!(s, "    pub const BASE: usize = {:#010x};", p.offset).unwrap();
        writeln!(s, "    /// Size of the mapped region, in bytes.").unwrap();
        writeln!(s, "    pub const RANGE: usize = {:#010x};", p.range).unwrap();
        writeln!(s, "    /// Vendor:library:name:version of the IP behind this window.").unwrap();
        writeln!(s, "    pub const VLNV: &str = {:?};", p.vlnv).unwrap();
        writeln!(s, "}}\n").unwrap();
    }

    // A slice of every peripheral, so callers can iterate the map at runtime
    // (logging it over UART at boot is the fastest way to confirm the bitstream
    // in the PL matches the binary running on the PS).
    writeln!(s, "/// Every AXI peripheral in the block design.").unwrap();
    writeln!(
        s,
        "pub const PERIPHERALS: [Peripheral; {}] = [",
        peripherals.len()
    )
    .unwrap();
    for p in peripherals {
        writeln!(
            s,
            "    Peripheral {{ instance: {:?}, vlnv: {:?}, base: {:#010x}, range: {:#010x} }},",
            p.instance, p.vlnv, p.offset, p.range
        )
        .unwrap();
    }
    writeln!(s, "];").unwrap();

    // Guard against two instances whose names differ only in punctuation, which
    // would otherwise collide into one module and silently drop a peripheral.
    let mut seen = BTreeSet::new();
    for p in peripherals {
        let module = sanitize(&p.instance);
        assert!(
            seen.insert(module.clone()),
            "xil_bindings: instance name {:?} collides with another peripheral as module `{module}`",
            p.instance
        );
    }

    s
}

fn sanitize(instance: &str) -> String {
    let mut s: String = instance
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect();
    s.make_ascii_lowercase();
    if s.starts_with(|c: char| c.is_ascii_digit()) {
        s.insert(0, '_');
    }
    // Vivado does not reserve Rust keywords, so a cell called `type` or `loop`
    // is legal in the block design and would emit a module that does not parse.
    if RUST_KEYWORDS.contains(&s.as_str()) {
        s.push('_');
    }
    s
}

/// Strict and reserved keywords that cannot be a module name. Weak keywords
/// (`union`, `macro_rules`) are fine as module names and are left out.
const RUST_KEYWORDS: &[&str] = &[
    "abstract", "as", "async", "await", "become", "box", "break", "const", "continue", "crate",
    "do", "dyn", "else", "enum", "extern", "false", "final", "fn", "for", "gen", "if", "impl",
    "in", "let", "loop", "match", "mod", "move", "mut", "override", "priv", "pub", "ref",
    "return", "self", "static", "struct", "super", "trait", "true", "try", "type", "typeof",
    "unsafe", "unsized", "use", "virtual", "where", "while", "yield",
];
